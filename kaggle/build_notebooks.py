def notebook(cells: "list[dict]") -> dict:
    return {
        "cells": cells,
        "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
                     "language_info": {"name": "python"}},
        "nbformat": 4, "nbformat_minor": 4,
    }


def kernel_metadata(slug: str, code_file: str, enable_internet: bool, dataset_sources: list, kernel_sources: list) -> dict:
    return {
        "id": f"{KAGGLE_USERNAME}/{slug}", "title": slug, "code_file": code_file,
        "language": "python", "kernel_type": "notebook", "is_private": True,
        "enable_gpu": True, "enable_tpu": False, "enable_internet": enable_internet,
        "dataset_sources": dataset_sources, "kernel_sources": kernel_sources, "model_sources": [],
        "competition_sources": ["image-matching-challenge-2025"],
        "docker_image": DOCKER_IMAGE, "machine_shape": "NvidiaTeslaT4",
    }


def main() -> None:
    commit = current_commit()
    targets = {
        "training": (training_cells(commit), kernel_metadata("sc4000-training", "training.ipynb", True, [], [])),
        "inference": (inference_cells(commit), kernel_metadata(
            "sc4000-inference", "inference.ipynb", False,
            ["oldufo/imc2024-packages-lightglue-rerun-kornia", "eduardtrulls/imc25-utils"],
            [f"{KAGGLE_USERNAME}/sc4000-training"],
        )),
    }
    for name, (cells, metadata) in targets.items():
        output_dir = Path(__file__).resolve().parent / name
        output_dir.mkdir(parents=True, exist_ok=True)
        (output_dir / metadata["code_file"]).write_text(json.dumps(notebook(cells), indent=1) + "\n")
        (output_dir / "kernel-metadata.json").write_text(json.dumps(metadata, indent=2) + "\n")
        print(f"wrote kaggle/{name}/{metadata['code_file']} ({len(cells)} cells, commit {commit})")


if __name__ == "__main__":
    main()
