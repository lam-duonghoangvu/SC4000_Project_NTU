"""Generate kaggle/training/training.ipynb and kaggle/inference/inference.ipynb (+ kernel-metadata.json).

`kaggle kernels push` uploads a single notebook, so every file under src/ and scripts/ is embedded
as a `%%writefile` cell that recreates the package in CODE_ROOT before it runs.
Do not edit the generated notebooks by hand; rerun this script, then push:

    python kaggle/build_notebooks.py && kaggle kernels push -p kaggle/training
"""

import json
import subprocess
from pathlib import Path

REPOSITORY_ROOT = Path(__file__).resolve().parents[1]
CODE_ROOT = "/kaggle/working/sc4000"
EMBEDDED_CODE_DIRS = ("src", "scripts")
KAGGLE_USERNAME = "dhvlam"
# Same image as the rank-4 kernel: the offline wheels (pycolmap 0.6.1, lightglue) are cp310.
DOCKER_IMAGE = "gcr.io/kaggle-private-byod/python@sha256:d8674e13fab653bf7fb8d9a102f2ae94036771ccb5c73f51888d881421e1f937"


def markdown_cell(text: str) -> dict:
    return {"cell_type": "markdown", "metadata": {}, "source": text.strip("\n").splitlines(keepends=True)}


def code_cell(text: str) -> dict:
    return {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [],
            "source": text.strip("\n").splitlines(keepends=True)}


def embedded_code_cells() -> "list[dict]":
    """One mkdir cell plus one `%%writefile` cell per source file, bodies byte-identical to the repo."""
    source_paths = sorted(
        path for directory in EMBEDDED_CODE_DIRS for path in (REPOSITORY_ROOT / directory).rglob("*.py")
        if "__pycache__" not in path.parts
    )
    target_dirs = sorted({f"{CODE_ROOT}/{path.parent.relative_to(REPOSITORY_ROOT)}" for path in source_paths})
    # IPython refuses %%writefile with an empty body, so empty files (package __init__.py) are touched instead
    empty_files = [f"{CODE_ROOT}/{path.relative_to(REPOSITORY_ROOT)}" for path in source_paths if not path.read_text()]
    setup_lines = ["!mkdir -p " + " ".join(target_dirs)] + (["!touch " + " ".join(empty_files)] if empty_files else [])
    cells = [markdown_cell("## Code (inlined from the repo by kaggle/build_notebooks.py)"),
             code_cell("\n".join(setup_lines))]
    for path in source_paths:
        file_content = path.read_text()
        if not file_content:
            continue
        cell = {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [],
                "source": [f"%%writefile {CODE_ROOT}/{path.relative_to(REPOSITORY_ROOT)}\n",
                           *file_content.splitlines(keepends=True)]}
        assert "".join(cell["source"][1:]) == file_content, f"embedding changed {path}"
        cells.append(cell)
    return cells


def locate_inputs_cell(slug_by_variable: "dict[str, str]") -> dict:
    """Python cell that finds each Kaggle input by slug, since the mount depth under /kaggle/input differs
    between Kaggle sessions (/kaggle/input/<slug> or nested deeper). Variables are reused as {VAR} in ! lines."""
    lines = [
        "import glob, os",
        "",
        "def kaggle_input_dir(slug):",
        "    for depth in range(4):",
        "        pattern = os.path.join('/kaggle/input', *['*'] * depth, slug)",
        "        matches = sorted(path for path in glob.glob(pattern) if os.path.isdir(path))",
        "        if matches:",
        "            return matches[0]",
        "    raise FileNotFoundError(f'{slug} is not mounted under /kaggle/input; attached inputs are listed above')",
        "",
        "!find /kaggle/input -maxdepth 3 -type d | head -40",
    ]
    lines += [f"{variable} = kaggle_input_dir({slug!r})" for variable, slug in slug_by_variable.items()]
    lines += [f"print('{variable} =', {variable})" for variable in slug_by_variable]
    return code_cell("\n".join(lines))


def current_commit() -> str:
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=REPOSITORY_ROOT,
                            capture_output=True, text=True).stdout.strip() or "unknown"
    dirty = subprocess.run(["git", "status", "--porcelain", *EMBEDDED_CODE_DIRS], cwd=REPOSITORY_ROOT,
                           capture_output=True, text=True).stdout.strip()
    return commit + ("+uncommitted" if dirty else "")


